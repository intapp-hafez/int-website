export type AuthKey = keyof typeof dict.en;

export function useAuthT() {
  const { lang, dir } = useI18n();
  const t = (k: AuthKey, vars?: Record<string, string>) => {
    let s = (dict[lang] as any)[k] ?? dict.en[k] ?? k;
    if (vars) for (const [vk, vv] of Object.entries(vars)) s = s.replaceAll(`{${vk}}`, vv);
    return s as string;
  };
  return { t, lang, dir };
}
