export type ClientTKey = keyof typeof dict.en;

export function useClientT() {
  const { lang, dir } = useI18n();
  const t = (k: ClientTKey) => (dict[lang as "en" | "ar"] ?? dict.en)[k] ?? dict.en[k];
  return { t, lang, dir, isRtl: dir === "rtl" };
}

